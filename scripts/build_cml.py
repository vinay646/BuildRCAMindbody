#!/usr/bin/env python3
"""Generates cml/MindbodyPlans.cml and the constraintModels entry of MB_Build_Data.json from the bundle data.

Every bundle (tier, Enterprise, Branded app) is a CML type with one relation per bundle component, and every
product is one CML type - the engine walks bundle components and needs a relation for each (else: "Unable to find
a relation in type ... for product ..."). Links: one Type link per product, one Port link per bundle component.
"""
import json, re, sys
DATA = 'force-app/main/default/staticresources/MB_Build_Data.json'
d = json.load(open(DATA))
names = {p['code']: p['name'] for p in d['products']}
for f in d.get('features', []):
    names[f['code']] = f['name']

# fixed type names for the products the rules use
fixed = {'MB-STR': 'Starter', 'MB-ACC': 'Accelerate', 'MB-ULT': 'Ultimate', 'MB-ENT': 'Enterprise',
         'MB-AIC': 'AIConciergeAddOn', 'MB-APP': 'BrandedApp', 'MB-APP-SET': 'BrandedAppSetup',
         'MB-PAY': 'MindbodyPayments', 'MB-HW-RDR': 'MobileCardReader', 'MB-HW-TRM': 'CountertopPaymentTerminal',
         'MB-HW-DOOR': 'DoorAccessKit',
         'MB-TAM': 'TechnicalAccountManagement', 'MB-DCV': 'CustomDataConversion', 'MB-MKT': 'MarketplaceFee', 'MB-SMS': 'SmsOverage'}
def tname(code):
    if code in fixed:
        return fixed[code]
    base = re.sub(r'[^A-Za-z0-9 ]', ' ', names[code]).title().replace(' ', '')
    return base + ('Feature' if code.startswith('MB-F-') else '')
prefix = {'MB-STR': 'str', 'MB-ACC': 'acc', 'MB-ULT': 'ult', 'MB-ENT': 'ent', 'MB-APP': 'app'}

bundles = d['bundles']
types, ports, rel_lines = {}, [], {}
for code in list(fixed) + [c for b in bundles.values() for g in b for c in [x['code'] for x in g['components']]]:
    types[tname(code)] = code
for parent, groups in bundles.items():
    lines = []
    for g in groups:
        lines.append('    // ' + g['name'])
        for c in g['components']:
            rel = prefix[parent] + '_' + tname(c['code']).lower()
            lines.append(f'    relation {rel} : {tname(c["code"])}[0..9999];')
            ports.append({'tag': rel, 'parent': parent, 'child': c['code']})
    rel_lines[parent] = lines

out = []
out.append('''// ============================================================================
// Mindbody Plans – constraint model (spec 12.3 product rules)
// GENERATED by scripts/build_cml.py from MB_Build_Data.json – do not edit by hand.
// ============================================================================
// Pattern of the org's QuantumBit Bundle model (release 262):
//   * a virtual Quote container that sees every quote line (cart-level rules),
//   * every product is one CML type (Type link), every bundle declares one relation per
//     bundle component (Port link to the ProductRelatedComponent) – loader step `constraints`.
// Design (phase 5): one opportunity and quote per account – every account, location included, can
// buy; billing follows the account's Payer Type. So "per location" rules are "per quote" here.
// ----------------------------------------------------------------------------

// CR-12: hierarchy-wide active locations (Quote > Hierarchy Location Count) from the sales transaction context
@(contextPath = "SalesTransaction.MbHierarchyLocationCount")
extern decimal HierarchyLocations;

// CR-11: the customer's prior system (Opportunity > Prior System, via Quote > Prior System)
@(contextPath = "SalesTransaction.MbPriorSystem")
extern string PriorSystem;

@(virtual = "true")
type Quote {
    @(sourceContextNode = "SalesTransaction.SalesTransactionItem")
    relation lineitems : LineItem;

    // CR-05 / CAT-05: AI Concierge is included in Ultimate – no paid add-on next to it
    message(lineitems[Ultimate] > 0 && lineitems[AIConciergeAddOn] > 0,
        "AI Concierge is already included in Ultimate – remove the AI Concierge add-on.", "Error");

    // CR-04 / CFG-03: Starter cannot take AI Concierge or Branded app
    message(lineitems[Starter] > 0 && lineitems[AIConciergeAddOn] > 0,
        "Starter can't add AI Concierge – choose Accelerate or Ultimate.", "Error");
    message(lineitems[Starter] > 0 && lineitems[BrandedApp] > 0,
        "Starter can't add Branded app – choose Accelerate or Ultimate.", "Error");

    // CR-01: one tier per location = one plan per quote (the quote's account is the location)
    constraint(lineitems[Starter] + lineitems[Accelerate] + lineitems[Ultimate] + lineitems[Enterprise] <= 1,
        "Only one plan (Starter, Accelerate, Ultimate or Enterprise) per quote – quote each location on its own account.");

    // CFG-13: no duplicate product per Ship-To = per quote. Tiers are covered by CR-01; add-ons sit in the
    // bundles (max 1); hardware and services may repeat (quantity). Recurring and usage products once only:
    constraint(lineitems[MindbodyPayments] <= 1, "Mindbody Payments is already on this quote – add it once per location.");
    constraint(lineitems[TechnicalAccountManagement] <= 1, "Technical Account Management is already on this quote – add it once per location.");
    constraint(lineitems[MarketplaceFee] <= 1, "Marketplace new-client fee is already on this quote – add it once per location.");
    constraint(lineitems[SmsOverage] <= 1, "SMS overage is already on this quote – add it once per location.");

    // CR-07: one Branded app per brand – once per quote here (across a brand's quotes: checked on assets, phase 6)
    constraint(lineitems[BrandedApp] <= 1,
        "Branded app is sold once per brand – keep one Branded app.");

    // Catalog guidance (Browse Products): grey out add-ons the tier on the quote cannot take
    rule(lineitems[Ultimate] > 0, "disable", "relation", "lineitems", "type", "AIConciergeAddOn",
        "message", "AI Concierge is already included in Ultimate.");
    rule(lineitems[Starter] > 0, "disable", "relation", "lineitems", "type", "AIConciergeAddOn",
        "message", "Starter can't add AI Concierge – choose Accelerate or Ultimate.");
    rule(lineitems[Starter] > 0, "disable", "relation", "lineitems", "type", "BrandedApp",
        "message", "Starter can't add Branded app – choose Accelerate or Ultimate.");

    // Catalog guidance: recommend Mindbody Payments when hardware is on the quote (CR-09)
    rule(lineitems[MobileCardReader], "recommend", "type", "MindbodyPayments", "message", "Hardware requires Mindbody Payments.");
    rule(lineitems[CountertopPaymentTerminal], "recommend", "type", "MindbodyPayments", "message", "Hardware requires Mindbody Payments.");
    rule(lineitems[DoorAccessKit], "recommend", "type", "MindbodyPayments", "message", "Hardware requires Mindbody Payments.");

    // CR-09: hardware needs Mindbody Payments – the configurator adds it (same pattern as QuantumBit's cart-level require)
    require(lineitems[MobileCardReader], lineitems[MindbodyPayments], "Hardware requires Mindbody Payments – added to the quote.");
    require(lineitems[CountertopPaymentTerminal], lineitems[MindbodyPayments], "Hardware requires Mindbody Payments – added to the quote.");
    require(lineitems[DoorAccessKit], lineitems[MindbodyPayments], "Hardware requires Mindbody Payments – added to the quote.");

    // CR-12: recommend Technical Account Management at 10+ locations in the hierarchy, Enterprise at 25+
    rule(HierarchyLocations >= 10 && lineitems[TechnicalAccountManagement] == 0, "recommend", "type", "TechnicalAccountManagement",
        "message", "10 or more locations in this customer's hierarchy – recommend Technical Account Management.");
    rule(HierarchyLocations >= 25 && lineitems[Enterprise] == 0, "recommend", "type", "Enterprise",
        "message", "25 or more locations in this customer's hierarchy – recommend the Enterprise plan.");

    // CR-11: recommend Custom data conversion when the opportunity's prior system is a competitor
    rule(PriorSystem != "None" && PriorSystem != "" && lineitems[CustomDataConversion] == 0, "recommend", "type", "CustomDataConversion",
        "message", "The customer is moving from another system – recommend Custom data conversion.");

    // CR-09 fallback message (shown if Payments is removed again)
    message((lineitems[MobileCardReader] + lineitems[CountertopPaymentTerminal] + lineitems[DoorAccessKit]) > 0
            && lineitems[MindbodyPayments] == 0,
        "Hardware requires Mindbody Payments – add Mindbody Payments (opt in) to the quote.", "Error");
}

// --- Base type ---
type LineItem;
''')
for parent in bundles:
    out.append(f'// --- {names[parent]} bundle ({parent}) ---')
    out.append(f'type {tname(parent)} : LineItem {{')
    out.extend(rel_lines[parent])
    out.append('}\n')
out.append('// --- Products without bundle structure ---')
for t, code in sorted(types.items(), key=lambda x: x[0]):
    if code not in bundles:
        out.append(f'type {t} : LineItem;   // {code} {names[code]}')
open('cml/MindbodyPlans.cml', 'w').write('\n'.join(out) + '\n')

cm = d['constraintModels'][0]
cm['types'] = dict(sorted(types.items()))
cm['ports'] = ports
open(DATA, 'w').write(json.dumps(d, indent=1, ensure_ascii=False) + '\n')
print(len(types), 'types,', len(ports), 'ports')
