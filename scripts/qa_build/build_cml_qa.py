#!/usr/bin/env python3
"""Generates cml/MindbodyPlans_QA.cml and scripts/qa_build/cml_links_qa.json: the dev org's Mindbody Plans model
(cml/MindbodyPlans.cml, same rules and messages) mapped onto the QA org's (mindbodysfs) own bundle design:
  * combined features MB-F-RES-PAS and MB-F-LEAD-CDB instead of RES / PAS / LEAD / CDB,
  * one AI Concierge product (MB-F-AIC): Accelerate's paid add-on and Ultimate / Enterprise included feature,
  * QA context attributes PriorSystem__c (Quote.Prior_system__c) and Locationcount__c (Quote.Location_count__c).
AI Concierge rules that only exist because dev has a separate paid add-on product (CR-05 "remove the add-on next to
Ultimate", and greying it out for Ultimate) are left out: in QA the add-on exists only inside Accelerate, and CR-01
allows one plan per quote, so it cannot sit next to Ultimate; the rule would fire on Ultimate's own included feature."""
import json

TYPES = {  # CML type -> QA product code
    'Starter': 'MB-STR', 'Accelerate': 'MB-ACC', 'Ultimate': 'MB-ULT', 'Enterprise': 'MB-ENT', 'BrandedApp': 'MB-APP',
    'BrandedAppSetup': 'MB-APP-SET', 'AiConcierge': 'MB-F-AIC', 'BusinessManagementFeature': 'MB-F-BM',
    'MindbodyAppListingFeature': 'MB-F-APPL', 'PosAndOnlinePaymentsFeature': 'MB-F-POS', 'BrandedWebWidgetsFeature': 'MB-F-WEB',
    'ResourceManagementPickASpotFeature': 'MB-F-RES-PAS', 'AdvancedReportingFeature': 'MB-F-REP', 'PromoCodesFeature': 'MB-F-PROMO',
    'EmailAndSmsMarketingFeature': 'MB-F-MKTG', 'LeadManagementDashboardFeature': 'MB-F-LEAD-CDB',
    'CountertopPaymentTerminal': 'MB-HW-TRM', 'CustomDataConversion': 'MB-DCV', 'DoorAccessKit': 'MB-HW-DOOR',
    'MarketplaceFee': 'MB-MKT', 'MindbodyPayments': 'MB-PAY', 'MobileCardReader': 'MB-HW-RDR', 'SmsOverage': 'MB-SMS',
    'TechnicalAccountManagement': 'MB-TAM'}
CODE2TYPE = {v: k for k, v in TYPES.items()}
NAMES = {'MB-F-AIC': 'AI Concierge', 'MB-F-BM': 'Business management', 'MB-F-APPL': 'Mindbody App Listing',
         'MB-F-POS': 'POS and Online Payments', 'MB-F-WEB': 'Branded web widgets and Customized Website',
         'MB-F-RES-PAS': 'Resource Management and Pick-a-Spot', 'MB-F-REP': 'Advanced Reporting', 'MB-F-PROMO': 'Promo Codes',
         'MB-F-MKTG': 'Email and SMS Marketing', 'MB-F-LEAD-CDB': 'Lead Management and Dashboard', 'MB-APP-SET': 'Branded app setup',
         'MB-HW-TRM': 'Countertop Payment Terminal', 'MB-DCV': 'Custom Data Conversion', 'MB-HW-DOOR': 'Door Access Kit',
         'MB-MKT': 'Marketplace new-client fee', 'MB-PAY': 'Mindbody Payments', 'MB-HW-RDR': 'Mobile Card Reader',
         'MB-SMS': 'SMS overage', 'MB-TAM': 'Technical Account Management'}
# QA bundle components (ProductRelatedComponent in mindbodysfs, 20 Nov 2026), in QA's sequence
BUNDLES = [
    ('Starter', 'MB-STR', 'str', [('Starter Group Child Components', ['MB-F-BM', 'MB-F-APPL', 'MB-F-POS', 'MB-F-WEB'])]),
    ('Accelerate', 'MB-ACC', 'acc', [('Accelerate Group Child Components', ['MB-F-BM', 'MB-F-APPL', 'MB-F-POS', 'MB-F-WEB', 'MB-F-RES-PAS', 'MB-F-REP', 'MB-F-PROMO']),
                                     ('Add-Ons', ['MB-F-AIC', 'MB-APP'])]),
    ('Ultimate', 'MB-ULT', 'ult', [('Ultimate Group Child Components', ['MB-F-BM', 'MB-F-APPL', 'MB-F-POS', 'MB-F-WEB', 'MB-F-RES-PAS', 'MB-F-REP', 'MB-F-PROMO',
                                                                       'MB-F-MKTG', 'MB-F-LEAD-CDB', 'MB-F-AIC']),
                                   ('Ultimate Add-Ons', ['MB-APP'])]),
    ('Enterprise', 'MB-ENT', 'ent', [('Enterprise Group Child Components', ['MB-F-BM', 'MB-F-APPL', 'MB-F-POS', 'MB-F-WEB', 'MB-F-RES-PAS', 'MB-F-REP', 'MB-F-PROMO',
                                                                           'MB-F-MKTG', 'MB-F-LEAD-CDB', 'MB-F-AIC']),
                                     ('Add-Ons', ['MB-APP'])]),
    ('BrandedApp', 'MB-APP', 'app', [('Branded App Child Group Component', ['MB-APP-SET'])]),
]

dev = open('cml/MindbodyPlans.cml').read()
head = dev[:dev.index('// --- Base type ---')]
# header + context attributes
head = head.replace('''// GENERATED by scripts/build_cml.py from MB_Build_Data.json – do not edit by hand.''',
                    '''// QA org (mindbodysfs) version – GENERATED by scripts/qa_build/build_cml_qa.py from the dev model
// cml/MindbodyPlans.cml: same rules and messages, mapped to QA's bundle design (see the script's notes).''')
head = head.replace('@(contextPath = "SalesTransaction.MbHierarchyLocationCount")', '@(contextPath = "SalesTransaction.Locationcount__c")')
head = head.replace('// CR-12: hierarchy-wide active locations (Quote > Hierarchy Location Count) from the sales transaction context',
                    '// CR-12: locations (QA: Quote > Location Count) from the sales transaction context')
head = head.replace('@(contextPath = "SalesTransaction.MbPriorSystem")', '@(contextPath = "SalesTransaction.PriorSystem__c")')
head = head.replace('// CR-11: the customer\'s prior system (Opportunity > Prior System, via Quote > Prior System)',
                    '// CR-11: the customer\'s prior system (QA: Quote > Prior System)')
# AI Concierge: one product in QA
cr05 = '''    // CR-05 / CAT-05: AI Concierge is included in Ultimate – no paid add-on next to it
    message(lineitems[Ultimate] > 0 && lineitems[AIConciergeAddOn] > 0,
        "AI Concierge is already included in Ultimate – remove the AI Concierge add-on.", "Error");
'''
assert cr05 in head; head = head.replace(cr05, '''    // CR-05 / CAT-05: AI Concierge is included in Ultimate – in QA the paid add-on exists only inside Accelerate and
    // CR-01 allows one plan per quote, so it cannot sit next to Ultimate (no separate rule needed)
''')
dis = '''    rule(lineitems[Ultimate] > 0, "disable", "relation", "lineitems", "type", "AIConciergeAddOn",
        "message", "AI Concierge is already included in Ultimate.");
'''
assert dis in head; head = head.replace(dis, '')
head = head.replace('AIConciergeAddOn', 'AiConcierge')

out = [head.rstrip() + '\n', '// --- Base type ---', 'type LineItem;', '']
ports = []
for tname, code, pre, groups in BUNDLES:
    out.append(f'// --- {tname} bundle ({code}) ---')
    out.append(f'type {tname} : LineItem {{')
    for gname, kids in groups:
        out.append(f'    // {gname}')
        for k in kids:
            rel = f'{pre}_{CODE2TYPE[k].lower()}'
            out.append(f'    relation {rel} : {CODE2TYPE[k]}[0..9999];')
            ports.append({'tag': rel, 'parent': code, 'child': k})
    out.append('}'); out.append('')
out.append('// --- Products without bundle structure ---')
bundles = {b[0] for b in BUNDLES}
for t in sorted(TYPES):
    if t not in bundles:
        out.append(f'type {t} : LineItem;   // {TYPES[t]} {NAMES.get(TYPES[t], "")}'.rstrip())
open('cml/MindbodyPlans_QA.cml', 'w').write('\n'.join(out) + '\n')
json.dump({'apiName': 'Mindbody_Plans', 'types': TYPES, 'ports': ports}, open('scripts/qa_build/cml_links_qa.json', 'w'), indent=1)
print(len(TYPES), 'types,', len(ports), 'ports')
